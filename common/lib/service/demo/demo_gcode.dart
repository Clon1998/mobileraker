/// The g-code files of the demo printer, with real g-code so the g-code
/// preview and exclude object have something to draw.
library;

import 'dart:math' as math;

/// One printable object of a demo file.
class DemoObject {
  const DemoObject(this.name, this.cx, this.cy, this.shape, this.size, {this.twist = 0, this.sides = 6});

  final String name;
  final double cx;
  final double cy;

  /// `box`, `cylinder` or `twist` (a polygon that turns while it grows).
  final String shape;

  /// Edge length of a box, diameter of the round shapes.
  final double size;

  /// Degrees a `twist` turns per layer.
  final double twist;

  /// Corners of a `twist`.
  final int sides;

  /// The outline at [layer], as moonraker reports it in `exclude_object`.
  List<List<double>> outline([int layer = 0]) {
    final r = size / 2;
    switch (shape) {
      case 'box':
        return [
          [cx - r, cy - r],
          [cx + r, cy - r],
          [cx + r, cy + r],
          [cx - r, cy + r],
        ];
      case 'twist':
        final turn = layer * twist * math.pi / 180;
        return [
          for (var i = 0; i < sides; i++)
            [cx + r * math.cos(turn + i * 2 * math.pi / sides), cy + r * math.sin(turn + i * 2 * math.pi / sides)],
        ];
      default:
        const steps = 32;
        return [
          for (var i = 0; i < steps; i++)
            [cx + r * math.cos(i * 2 * math.pi / steps), cy + r * math.sin(i * 2 * math.pi / steps)],
        ];
    }
  }

  Map<String, dynamic> toExcludeObject() => {
        'name': name,
        'center': [cx, cy],
        'polygon': [
          for (final p in outline()) [double.parse(_r(p[0])), double.parse(_r(p[1]))],
        ],
      };
}

/// A g-code file of the demo printer.
class DemoGCodeFile {
  DemoGCodeFile({
    required this.seconds,
    required this.material,
    required this.color,
    required this.grams,
    required this.nozzle,
    required this.bed,
    required this.layers,
    required this.objects,
    required this.ageHours,
  });

  final int seconds;
  final String material;
  final String color;
  final double grams;
  final int nozzle;
  final int bed;
  final int layers;
  final List<DemoObject> objects;
  final double ageHours;

  static const layerHeight = 0.2;

  double get height => layers * layerHeight;

  late final String content = _generate();

  /// Filament the g-code extrudes, measured while generating it.
  double get filamentMm {
    if (content.isEmpty) return 0;
    return _filamentMm;
  }

  double _filamentMm = 0;

  int get size => content.length;

  /// Slicer metadata as `server.files.metadata` returns it.
  Map<String, dynamic> metadata(double now) => {
        'size': size,
        'modified': now - ageHours * 3600,
        'uuid': null,
        'slicer': 'OrcaSlicer',
        'slicer_version': '2.3.0',
        'gcode_start_byte': 900,
        'gcode_end_byte': size - 200,
        'layer_count': layers,
        'object_height': height,
        'estimated_time': seconds,
        'nozzle_diameter': 0.4,
        'layer_height': layerHeight,
        'first_layer_height': layerHeight,
        'first_layer_extr_temp': nozzle.toDouble(),
        'first_layer_bed_temp': bed.toDouble(),
        'chamber_temp': 0.0,
        'filament_name': 'Generic $material',
        'filament_type': material,
        'filament_colors': [color],
        'extruder_colors': [color],
        'filament_total': filamentMm,
        'filament_weight_total': grams,
        'filament_weights': [grams],
        'thumbnails': <dynamic>[],
      };

  String _generate() {
    final out = StringBuffer()
      ..writeln('; generated by OrcaSlicer 2.3.0 (Mobileraker demo printer)')
      ..writeln('; estimated printing time (normal mode) = ${seconds ~/ 3600}h ${seconds % 3600 ~/ 60}m')
      ..writeln('; filament_type = $material');
    for (final o in objects) {
      final poly = o.outline().map((p) => '[${_r(p[0])},${_r(p[1])}]').join(',');
      out.writeln('EXCLUDE_OBJECT_DEFINE NAME=${o.name} CENTER=${_r(o.cx)},${_r(o.cy)} POLYGON=[$poly]');
    }
    out
      ..writeln('M140 S$bed')
      ..writeln('M104 S$nozzle')
      ..writeln('G28')
      ..writeln('M190 S$bed')
      ..writeln('M109 S$nozzle')
      ..writeln('G90')
      ..writeln('M83')
      ..writeln('G1 Z0.3 F600')
      ..writeln('G1 X10 Y10 F6000')
      ..writeln('G1 X10 Y120 E12 F1500 ; purge line');

    var e = 0.0;
    for (var layer = 0; layer < layers; layer++) {
      final z = (layer + 1) * layerHeight;
      out
        ..writeln(';LAYER_CHANGE')
        ..writeln(';Z:${_r(z)}')
        ..writeln('SET_PRINT_STATS_INFO CURRENT_LAYER=${layer + 1}')
        ..writeln('G1 Z${_r(z)} F600');
      for (final o in objects) {
        final points = o.outline(layer);
        out
          ..writeln('EXCLUDE_OBJECT_START NAME=${o.name}')
          ..writeln('G1 E-0.6 F2400')
          ..writeln('G0 X${_r(points.first[0])} Y${_r(points.first[1])} F9000')
          ..writeln('G1 E0.6 F2400');
        for (var i = 1; i <= points.length; i++) {
          final p = points[i % points.length];
          final prev = points[i - 1];
          final d = math.sqrt(math.pow(p[0] - prev[0], 2) + math.pow(p[1] - prev[1], 2)) * 0.0333;
          e += d;
          out.writeln('G1 X${_r(p[0])} Y${_r(p[1])} E${d.toStringAsFixed(4)} F3000');
        }
        out.writeln('EXCLUDE_OBJECT_END NAME=${o.name}');
      }
    }
    _filamentMm = double.parse(e.toStringAsFixed(1));
    out
      ..writeln('G1 E-2 F2400')
      ..writeln('G0 Z${_r(height + 10)} F600')
      ..writeln('M104 S0')
      ..writeln('M140 S0')
      ..writeln('M107')
      ..writeln('; end of print');
    return out.toString();
  }
}

String _r(double v) => v.toStringAsFixed(2);

/// Objects laid out in a grid around the bed center.
List<DemoObject> _grid(String prefix, int count, String shape, double size, {double gap = 12}) {
  final cols = math.sqrt(count).ceil();
  final rows = (count / cols).ceil();
  final pitch = size + gap;
  return [
    for (var i = 0; i < count; i++)
      DemoObject(
        '${prefix}_${i + 1}',
        125 + (i % cols - (cols - 1) / 2) * pitch,
        125 + (i ~/ cols - (rows - 1) / 2) * pitch,
        shape,
        size,
      ),
  ];
}

